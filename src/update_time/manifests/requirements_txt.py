"""Read requirements.txt files: their pins and other requirements, whether they are compiled, and what compiled them."""

import os
import re
import shlex
from dataclasses import dataclass
from enum import StrEnum
from pathlib import Path
from typing import Self

from update_time.domain.dependency import PinnedDependency
from update_time.domain.line import located_lines
from update_time.markers.marker import parse_marker
from update_time.markers.reference import SteeredReference
from update_time.primitives.command import Command

_AUTOGENERATED = re.compile(r"autogenerated by (pip-compile|uv)")
# A compiled file annotates a pin with the sources it came from, in a comment such as `# via -r requirements.in`. An
# annotation can name several, as in `# via -c c.txt, -r a.in, -r b.in`, or list them on the lines below a bare
# `# via`, one `#   -r a.in` per line. A `-c` names a constraint file, which is not a source.
_ANNOTATION = re.compile(r"#\s*(via\b.*|-r\s.*)")
_SOURCE_ANNOTATION = re.compile(r"(?:^|\s)-r\s+([^\s,]+)")
# The header of a compiled file records the command that compiled it, and that command the file it wrote to. uv records
# the options as they were typed, pip-compile as `--output-file=<path>`.
_COMMAND = re.compile(r"^#\s+((?:uv pip compile|pip-compile)(?:[ \t].*)?)$", re.MULTILINE)
# uv records a relative exclude-newer as typed, so `--exclude-newer "7 days"` reaches the header without its quotes.
_EXCLUDE_NEWER_OPTIONS = ("--exclude-newer", "--exclude-newer-package")
_OUTPUT = re.compile(r"(?:^|\s)(?:-o|--output-file)(?:=|\s+)(\S+)")

# Where a requirement line starts: the package name, optionally indented and optionally extra'd, and whatever space
# follows it. Indentation counts as pip strips a line before parsing it (`req_file.ignore_comments`), so an indented
# line is a requirement like any other. Its parts carry names of their own, since the lookahead below needs them
# without the capturing group.
_NAME = r"[A-Za-z0-9][A-Za-z0-9._-]*"
_EXTRAS = r"(?:\[[^\]]*\])?"
_REQUIREMENT_NAME = rf"^\s*(?P<dependency>{_NAME}){_EXTRAS}\s*"
# The characters a version holds, and the lookahead that requires it to end its specifier: nothing a version or a
# wildcard could go on with may follow, and no comma introducing a second specifier, which PEP 440 lets space
# precede. So `==4.15.*` names a range and `==4.15.0 ,!=4.15.1` names two specifiers, and neither is an exact pin.
_VERSION = r"[A-Za-z0-9][A-Za-z0-9._!+-]*"
_VERSION_ENDS = r"(?![A-Za-z0-9._!+*,-])(?!\s*,)"
# Match an exact pin: the name followed by `==` and a version that ends there. Only such a pin is updated.
EXACT_PIN_REFERENCE = re.compile(_REQUIREMENT_NAME + rf"==\s*(?P<version>{_VERSION}){_VERSION_ENDS}")
# The same pin without the capture groups, so the pattern below can hold a copy of it in a lookahead. Naming a
# group twice in one pattern is an error, and both patterns capture the dependency.
_EXACT_PIN = rf"^\s*{_NAME}{_EXTRAS}\s*==\s*{_VERSION}{_VERSION_ENDS}"
# Match a requirement that pins no exact version, which is any requirement the pattern above does not match: the
# lookahead rules out an exact pin, so a `==` reaching here names a range or one specifier of several. Such a
# requirement pins no version to update, but the project behind it is checked all the same. An option line (`-r`,
# `--index-url`), a comment line, and a direct reference (`name @ url`, a bare URL) match none of that.
LOOSE_REQUIREMENT_REFERENCE = re.compile(rf"(?!{_EXACT_PIN})" + _REQUIREMENT_NAME + r"(?:==|===|[<>!~]=|[<>]|[;#]|$)")
# The filename suffixes pip installs as a local archive rather than resolving as a requirement (its
# `ARCHIVE_EXTENSIONS`). A filename with no path in front of it, `mypkg-1.0.tar.gz`, is spelled like a bare
# requirement, so the pattern above matches it and PyPI would be asked for a package by that name.
_ARCHIVE_SUFFIXES = (".zip", ".whl", ".tar.gz", ".tar.bz2", ".tar", ".tgz", ".tar.xz", ".txz", ".tlz", ".tar.lzma")


def is_compiled(path: Path) -> bool:
    """Return whether the requirements file is compiled or locked.

    A requirements file is treated as compiled when it carries `--hash=` lines (pip requires every requirement to be
    hashed, so the file is fully locked), an autogenerated pip-compile/uv header, or a sibling `.in` source file.
    """
    contents = path.read_text()
    if "--hash=" in contents:
        return True
    if _AUTOGENERATED.search(contents):
        return True
    return (sibling := path.parent / f"{path.stem}.in") != path and sibling.exists()


class CompiledBy(StrEnum):
    """A tool that compiles a requirements file, named as its command starts."""

    UV = "uv"
    PIP_COMPILE = "pip-compile"


class Unrecompilable(StrEnum):
    """Why Update-time cannot recompile a compiled requirements file."""

    NO_COMMAND = "its header does not record a command Update-time can run"
    NO_OUTPUT = "it was compiled to standard output"
    OTHER_OUTPUT = "its header records another file as its output"


def _command(command_line: str) -> Command | None:
    """Return the command the line spells, or None where a shell cannot split it, as with an unclosed quote."""
    try:
        return Command(*_with_exclude_newer_values_joined(shlex.split(command_line)))
    except ValueError:
        return None


def _with_exclude_newer_values_joined(words: list[str]) -> list[str]:
    """Return the words with each exclude-newer uv recorded with a space, such as `7 days`, joined into one word."""
    joined: list[str] = []
    for word in words:
        if len(joined) > 1 and joined[-2] in _EXCLUDE_NEWER_OPTIONS and joined[-1][-1:].isdigit() and word.isalpha():
            joined[-1] = f"{joined[-1]} {word}"
        else:
            joined.append(word)
    return joined


@dataclass(frozen=True)
class CompiledRequirementsTxt:
    """A requirements file a tool compiled, with the command its header records, its sources, and its pins."""

    path: Path
    command: Command | None
    source_names: tuple[str, ...]  # Each once, spelled as the annotations write it
    pins: tuple[PinnedDependency, ...]  # In the order the exact pins appear in the file

    @classmethod
    def read(cls, path: Path) -> Self:
        """Read the compiled requirements file at the path."""
        contents = path.read_text()
        command = _command(match[1]) if (match := _COMMAND.search(contents)) else None
        annotations = _ANNOTATION.findall(contents)
        names = dict.fromkeys(name for annotation in annotations for name in _SOURCE_ANNOTATION.findall(annotation))
        pins = (EXACT_PIN_REFERENCE.match(line) for line in contents.splitlines())
        return cls(
            path,
            command,
            tuple(names),
            tuple(PinnedDependency(pin["dependency"], pin["version"]) for pin in pins if pin),
        )

    @property
    def unrecompilable(self) -> Unrecompilable | None:
        """Return why Update-time cannot recompile the file, or None where it can.

        A recompile reads the pins it keeps from the output, so Update-time recompiles only a file the command writes.
        """
        if not self.command:
            return Unrecompilable.NO_COMMAND
        if not self._output_name:
            return Unrecompilable.NO_OUTPUT
        return None if self._output_parts else Unrecompilable.OTHER_OUTPUT

    @property
    def compiled_by(self) -> CompiledBy | None:
        """Return the tool the header's command runs, or None where the header does not record a command."""
        return CompiledBy(self.command[0]) if self.command else None

    @property
    def recompile_command(self) -> Command | None:
        """Return the command the header records where Update-time can recompile the file with it, or None."""
        return None if self.unrecompilable else self.command

    @property
    def _output_name(self) -> str | None:
        """Return the output the command writes to, spelled as written, or None for standard output.

        Where the command does not name an output, pip-compile writes beside the source it names, with `.txt` in place
        of the source's suffix. A command that does not name a source compiles `requirements.in`.
        """
        if not self.command:
            return None
        if output := _OUTPUT.search(str(self.command)):
            return None if output[1] == "-" else output[1]  # pip-compile writes the output `-` to standard output
        if self.compiled_by is CompiledBy.PIP_COMPILE:
            return str(Path(self._named_source_name or "requirements.in").with_suffix(".txt"))
        return None

    @property
    def _named_source_name(self) -> str | None:
        """Return the first source the command names, spelled as the annotations write it, or None for none."""
        return next((word for word in self.command or () if word in self.source_names), None)

    @property
    def compile_directory(self) -> Path:
        """Return the directory the file was compiled in: its path, less the output path the command records.

        Where the command does not record an output that ends the file's path, the file's own directory is returned.
        """
        if output_parts := self._output_parts:
            return Path(*self.path.parts[: -len(output_parts)])
        return self.path.parent

    @property
    def _output_parts(self) -> tuple[str, ...]:
        """Return the parts of the output path the command records, where they end the file's path, or none."""
        output_parts = Path(os.path.normpath(output)).parts if (output := self._output_name) else ()
        return output_parts if output_parts and self.path.parts[-len(output_parts) :] == output_parts else ()

    @property
    def first_source(self) -> Path:
        """Return the source the command names first, or the source the annotations name first where it names none."""
        named = self._named_source_name
        return self.sources[self.source_names.index(named) if named else 0]

    @property
    def sources(self) -> tuple[Path, ...]:
        """Return the sources the annotations name, each relative to the directory the file was compiled in."""
        return tuple(Path(os.path.normpath(self.compile_directory / name)) for name in self.source_names)


def declarations(path: Path) -> list[SteeredReference]:
    """Return the requirements in the file, each with its marker and with the exact version it pins, if any."""
    requirements = []
    for line in located_lines(path, path.read_text().splitlines(keepends=True)):
        if pin := EXACT_PIN_REFERENCE.match(line.text):
            dependency, version = pin["dependency"], pin["version"]
        elif requirement := LOOSE_REQUIREMENT_REFERENCE.match(line.text):
            dependency, version = requirement["dependency"], ""
        else:
            continue
        requirements.append(SteeredReference(dependency, version, line.location, marker=parse_marker(line)))
    return requirements


def holds_line(path: Path, line: str) -> bool:
    """Return whether the requirements file holds the line, whole."""
    return line in path.read_text().splitlines()


def prepend_line(path: Path, line: str) -> None:
    """Write the line at the top of the requirements file."""
    path.write_text(f"{line}\n{path.read_text()}")


def names_an_archive(dependency: str) -> bool:
    """Return whether the requirement names a local archive, which pip installs rather than resolving."""
    return dependency.endswith(_ARCHIVE_SUFFIXES)
