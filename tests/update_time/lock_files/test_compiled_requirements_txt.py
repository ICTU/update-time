"""Unit tests for the compiled requirements.txt file format, with file I/O mocked."""

import unittest
from pathlib import Path

from update_time.lock_files import compiled_requirements_txt
from update_time.primitives.command import Command

from tests.mutation import Mutation, kills
from tests.update_time.lock_files.helpers import requirements_compiled_by_uv
from tests.update_time.manifests.helpers import requirements_file


class IsCompiledTest(unittest.TestCase):
    """Unit tests for detecting compiled/locked requirements files."""

    def test_hash_pinned(self):
        """Test that a hash-pinned (fully locked) file is compiled."""
        self.assertTrue(
            compiled_requirements_txt.is_compiled(requirements_file("flask==1.0 \\\n    --hash=sha256:abc\n"))
        )

    def test_autogenerated_header(self):
        """Test that a pip-compile/uv autogenerated header marks the file as compiled."""
        self.assertTrue(
            compiled_requirements_txt.is_compiled(requirements_file("# autogenerated by pip-compile\nflask==1.0\n"))
        )

    def test_sibling_in_file(self):
        """Test that a sibling .in source file marks the file as compiled."""
        self.assertTrue(compiled_requirements_txt.is_compiled(requirements_file("flask==1.0\n", sibling_in=True)))

    def test_plain_requirements(self):
        """Test that a plain hand-written requirements file is not compiled."""
        self.assertFalse(compiled_requirements_txt.is_compiled(requirements_file("flask==1.0\n")))


class SourceNamesTest(unittest.TestCase):
    """Unit tests for reading the sources a compiled requirements file names."""

    @kills(
        Mutation(
            compiled_requirements_txt.CompiledRequirementsTxt.read,
            "if not names and command:",
            "if False:",
            "Update-time misses the source that the command of an old pip-compile file names",
        )
    )
    def test_the_sources_the_file_names(self):
        """Test that the sources are what the annotations name, each once, or else the `.in` files the command names."""
        cases = {
            "one source": ("six==1.16.0\n    # via -r requirements.in\n", ("requirements.in",)),
            "a block of annotations": (
                "six==1.16.0\n    # via\n    #   -c c.txt\n    #   -r nested.in\n    #   -r requirements.in\n",
                ("nested.in", "requirements.in"),
            ),
            "a line of annotations": (
                "six==1.16.0               # via -c c.txt, -r requirements.in, -r nested.in\n",
                ("requirements.in", "nested.in"),
            ),
            "a source in another directory": ("six==1.17.0\n    # via -r ../dev.in\n", ("../dev.in",)),
            "a comment other than an annotation": (
                "# Install with: pip install --require-hashes -r requirements.txt\nsix==1.16.0\n",
                (),
            ),
            "a source two pins name": (
                "idna==3.10\n    # via -r requirements.in\nsix==1.16.0\n    # via -r requirements.in\n",
                ("requirements.in",),
            ),
            "a header naming a source, without annotations": (
                (
                    "#\n# This file is autogenerated by pip-compile\n# To update, run:\n#\n"
                    "#    pip-compile job-requirements.in\n#\napache-beam==2.24.0\n"
                ),
                ("job-requirements.in",),
            ),
        }
        for case, (contents, expected) in cases.items():
            with self.subTest(case):
                self.assertEqual(
                    compiled_requirements_txt.CompiledRequirementsTxt.read(requirements_file(contents)).source_names,
                    expected,
                )


class OutputNameTest(unittest.TestCase):
    """Unit tests for reading the output path the header of a compiled requirements file records."""

    @kills(
        Mutation(
            compiled_requirements_txt.CompiledRequirementsTxt._output_name,
            'return None if output[1] == "-" else output[1]',
            "return output[1]",
            "Update-time reads the standard output pip-compile wrote to as a file named -",
        )
    )
    def test_the_output_the_header_records(self):
        """Test that the output is where the header's command writes, and None where Update-time cannot name a file."""
        uv = "# This file was autogenerated by uv via the following command:\n#    uv pip compile {}\nsix==1.16.0\n"
        pip_compile = (
            "#\n# This file is autogenerated by pip-compile with Python 3.15\n# by the following command:\n#\n"
            "#    pip-compile {}\n#\nsix==1.16.0\n"
        )
        cases = {
            "uv's short option": (uv.format("docs/a.in -o docs/a.txt"), "docs/a.txt"),
            "uv's long option": (uv.format("docs/a.in --output-file docs/a.txt"), "docs/a.txt"),
            "uv's option after a value with a space": (
                uv.format("docs/a.in --exclude-newer 7 days -o docs/a.txt"),
                "docs/a.txt",
            ),
            "pip-compile's option": (pip_compile.format("--output-file=docs/a.txt docs/a.in"), "docs/a.txt"),
            "pip-compile's standard output": (pip_compile.format("--output-file=- docs/a.in"), None),
            "no output": (uv.format("docs/a.in"), None),
            "a custom command": (uv.replace("uv pip compile {}", "make lock -o docs/a.txt"), None),
            "a command with an unclosed quote": (uv.format('"docs/a.in -o docs/a.txt'), None),
        }
        for case, (contents, expected) in cases.items():
            with self.subTest(case):
                self.assertEqual(
                    compiled_requirements_txt.CompiledRequirementsTxt.read(requirements_file(contents))._output_name,
                    expected,
                )


class CommandTest(unittest.TestCase):
    """Unit tests for reading the command the header of a compiled requirements file records."""

    def test_an_exclude_newer_uv_records_with_a_space_is_one_value(self):
        """Test that an exclude-newer the header records without quotes, such as `7 days`, is read as one word."""
        cases = {
            "the run's exclude-newer": ("--exclude-newer 7 days", ("--exclude-newer", "7 days")),
            "a package's exclude-newer": (
                "--exclude-newer-package flask=7 days",
                ("--exclude-newer-package", "flask=7 days"),
            ),
        }
        for case, (options, expected) in cases.items():
            with self.subTest(case):
                contents = requirements_compiled_by_uv("base.in", options=options)
                command = compiled_requirements_txt.CompiledRequirementsTxt.read(requirements_file(contents)).command
                self.assertEqual(
                    command, Command("uv", "pip", "compile", "base.in", "-o", "requirements.txt", *expected)
                )


class FirstSourceTest(unittest.TestCase):
    """Unit tests for the source of a compiled requirements file that Update-time writes the managed-by comment into."""

    @kills(
        Mutation(
            compiled_requirements_txt.CompiledRequirementsTxt.first_source,
            "if named else 0]",
            "if named else -1]",
            "the managed-by comment goes into another source than the one annotated first",
        )
    )
    def test_the_source_annotated_first_where_the_command_names_none_of_the_annotated_sources(self):
        """Test that the first source is the one annotated first, where the command names only a source holding `-r`."""
        compiled = compiled_requirements_txt.CompiledRequirementsTxt(
            Path("requirements.txt"),
            Command("uv", "pip", "compile", "all.in", "-o", "requirements.txt"),
            source_names=("base.in", "dev.in"),
            pins=(),
        )
        self.assertEqual(compiled.first_source, Path("base.in"))
